#!/bin/sh
# Casper workspace hooks: per-worktree ports and the info panel.
# Usage: scripts/casper.sh setup|info|clear|teardown
set -eu

# Resolve the repo root from the script location, not the cwd.
root=$(cd "$(dirname "$0")/.." && pwd)

# True inside a Casper terminal that has the CLI; the panel is optional,
# so every caller treats "false" as a silent no-op.
has_casper() {
	[ -n "${CASPER_WORKSPACE_ID:-}" ] && command -v casper >/dev/null 2>&1
}

# Give a worktree workspace its own ports, from the band Casper reserved
# (CASPER_PORT .. CASPER_PORT + 9). The main checkout has no CASPER_PORT
# and keeps the default ports.
setup() {
	if [ -n "${CASPER_PORT:-}" ]; then
		web_port=$CASPER_PORT
		server_port=$((CASPER_PORT + 1))
		redis_port=$((CASPER_PORT + 2))
		# Valid both as a Makefile include and as a sh file: no spaces around "=".
		cat >"$root/.env.casper" <<ENV
# Generated by scripts/casper.sh setup. Do not edit.
COMPOSE_PROJECT_NAME=intothefray-$CASPER_PORT
WEB_PORT=$web_port
PORT=$server_port
REDIS_PORT=$redis_port
REDIS_URL=redis://localhost:$redis_port/0
ALLOWED_ORIGINS=http://localhost:$web_port
VITE_API_URL=http://localhost:$server_port
ENV
	fi
	cd "$root"
	make web-install
	go mod download
}

# Publish the endpoints to the info panel. The ports come from the
# environment (exported by make from .env.casper), never recomputed.
info() {
	has_casper || return 0
	web_port=${WEB_PORT:-5173}
	server_port=${PORT:-8080}
	redis_port=${REDIS_PORT:-6379}

	# BSD mktemp only substitutes trailing Xs, so add the extension after.
	file=$(mktemp /tmp/casper-info.XXXXXX) || return 0
	mv "$file" "$file.md" && file=$file.md

	cat >"$file" <<DOC
# Into The Fray — workspace stack

## Endpoints

| Endpoint      | URL                                     |
| ------------- | --------------------------------------- |
| Web app       | <http://localhost:$web_port>            |
| Server health | <http://localhost:$server_port/healthz> |

## Redis

\`\`\`
redis-cli -p $redis_port
\`\`\`

Restart with \`casper run\`.
DOC
	casper info set --file "$file" >/dev/null 2>&1 || true
	rm -f "$file"
}

clear_info() {
	has_casper || return 0
	casper info clear >/dev/null 2>&1 || true
}

# Stop this workspace's containers. Failure is ignored: the container
# engine may not be running, and teardown must not block deletion.
teardown() {
	clear_info
	cd "$root"
	make app-down || true
}

case "${1:-}" in
setup) setup ;;
info) info ;;
clear) clear_info ;;
teardown) teardown ;;
*)
	echo "usage: $0 setup|info|clear|teardown" >&2
	exit 2
	;;
esac
