#!/bin/sh
# Optional Casper workspace support: per-worktree ports and the info panel.
# Nothing else in the project depends on this script.
# Usage: scripts/casper.sh setup|dev|teardown
#
# Known limit: for make dev, the Makefile applies the variables that .env and
# .env.local assign on top of the environment, so a value set in either file
# (a PORT, an APP_INSTANCE) wins over the value of .env.casper.
set -eu

# Resolve the repo root from the script location, not the cwd.
root=$(cd "$(dirname "$0")/.." && pwd)

# True inside a Casper terminal that has the CLI; the panel is optional,
# so every caller treats "false" as a silent no-op.
has_casper() {
	[ -n "${CASPER_WORKSPACE_ID:-}" ] && command -v casper >/dev/null 2>&1
}

# Export every variable of .env.casper (written by setup) so that make,
# compose and air see this workspace's ports. Absent in the main
# checkout, which keeps the default ports.
load_env() {
	[ -f "$root/.env.casper" ] || return 0
	set -a
	. "$root/.env.casper"
	set +a
}

# The instance name shown in the browser tab title: the worktree's branch,
# or its directory name when detached. Characters outside A-Za-z0-9._/-
# become "-" so that the value needs no quoting in a sh file.
instance_name() {
	name=$(git -C "$root" branch --show-current 2>/dev/null || true)
	if [ -z "$name" ]; then
		name=$(basename "$root")
	fi
	# printf, not echo: tr would turn a trailing newline into "-".
	printf '%s' "$name" | tr -c 'A-Za-z0-9._/-' '-'
}

# Give a worktree workspace its own ports, from the band Casper reserved
# (CASPER_PORT .. CASPER_PORT + 9), and name its instance after the branch.
# The main checkout has no CASPER_PORT: default ports, no instance name.
setup() {
	if [ -n "${CASPER_PORT:-}" ]; then
		web_port=$CASPER_PORT
		server_port=$((CASPER_PORT + 1))
		redis_port=$((CASPER_PORT + 2))
		instance=$(instance_name)
		# Sourced as a sh file: no spaces around "=".
		cat >"$root/.env.casper" <<ENV
# Generated by scripts/casper.sh setup. Do not edit.
COMPOSE_PROJECT_NAME=intothefray-$CASPER_PORT
WEB_PORT=$web_port
PORT=$server_port
REDIS_PORT=$redis_port
REDIS_URL=redis://localhost:$redis_port/0
APP_INSTANCE=$instance
ENV
	fi
	cd "$root"
	make web-install
	go mod download
}

# Publish the endpoints of the dev stack to the info panel. `casper info set`
# replaces the whole panel, so this writes a complete document. The ports come
# from the environment that dev loaded from .env.casper, never recomputed.
info() {
	has_casper || return 0
	web_port=${WEB_PORT:-8080}
	server_port=${PORT:-9000}
	redis_port=${REDIS_PORT:-6379}

	casper info set - >/dev/null 2>&1 <<DOC || true
# Into The Fray — dev stack

## Endpoints

| Endpoint      | URL                                     |
| ------------- | --------------------------------------- |
| Web app       | <http://localhost:$web_port>            |
| Server health | <http://localhost:$server_port/healthz> |

## Redis

\`\`\`
redis-cli -p $redis_port
\`\`\`

Restart with \`casper run\`.
DOC
}

clear_info() {
	has_casper || return 0
	casper info clear >/dev/null 2>&1 || true
}

# Start the hot-reload stack with this workspace's ports and list its URLs
# in the info panel. make is not exec'd so that the EXIT trap can clear the
# panel. make dev ends with `kill 0` on the process group, which signals this
# shell too: the TERM trap turns that into a normal exit, and the EXIT trap
# then clears the panel once.
dev() {
	load_env
	cd "$root"
	info
	trap clear_info EXIT
	trap 'exit 130' INT
	trap 'exit 143' TERM
	make dev
}

# Remove this workspace's Redis and Caddy containers, which make dev starts
# detached (infra-up) and leaves up when it stops. Failure is ignored: the
# container engine may not be running, and teardown must not block deletion.
teardown() {
	# The environment carries COMPOSE_PROJECT_NAME and the ports to compose.
	load_env
	clear_info
	cd "$root"
	make app-down || true
}

case "${1:-}" in
setup) setup ;;
dev) dev ;;
teardown) teardown ;;
*)
	echo "usage: $0 setup|dev|teardown" >&2
	exit 2
	;;
esac
